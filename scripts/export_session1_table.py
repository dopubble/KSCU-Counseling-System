def main():
    assignment = assign_clients()
    rows = schedule_all(assignment)
    matched = sorted([r for r in rows if r["datetime"]], key=lambda r: r["datetime"])

    out = Path(__file__).resolve().parents[1] / "data" / "import" / "session1_schedule_full_table.csv"
    table = []
    for r in matched:
        kn, cn = r["counselor"], r["client"]
        note, client_req = CLIENT_META.get(cn, ("", ""))
        counselor_req = COUNSELOR_REQ.get(kn, "")
        dt = r["datetime"].strftime("%Y-%m-%d %H:%M")
        table.append([kn, cn, dt, note, client_req, counselor_req])

    with out.open("w", encoding="utf-8-sig", newline="") as f:
        w = csv.writer(f)
        w.writerow(["상담사", "내담자", "1회기", "내담자 비고", "내담자 요구 일정", "상담사 요구 일정"])
        w.writerows(table)

    print(f"Wrote {len(table)} rows to {out}")


if __name__ == "__main__":
    main()
